#!/usr/bin/env python3
"""
Generate Niubash completion TOML from WinuxCmd help output.

The generator has three input modes:
  1. Live probing: parse `winuxcmd.exe --help` for the applet inventory, then
     each applet's `winuxcmd <applet> --help` (default; requires the exe).
  2. `--from-corpus <dir>`: replay committed `*.help` transcripts instead of
     running the exe. Used by scripts/test-winuxcmd-completions.py so the
     golden check is deterministic and CI-runnable without the binary.
  3. `--capture-corpus <dir>`: write the raw per-applet transcripts alongside
     generation, so a live run can refresh the committed corpus fixture.

Outputs:
  - One completion TOML per applet under --out-dir (one file per applet so a
    user override is a plain same-named file drop, matching the runtime's
    stem == command override rule).
  - --rust-module: a generated Rust source that embeds every TOML via
    include_str!, consumed by ExternalCompletionPlugin::new().

The generated TOML is intentionally static. Runtime completion stays reserved
for values that are truly environment-dependent.

Help text is the specification. Where the help only says `ARG`, the flag value
stays opaque (no values_from), because completing filenames as the generic
fallback is the honest default; path completion is asserted only when the
value hint names a path-ish placeholder (FILE, DIR, ...) or the flag appears
in the curated PATH_VALUE_NAMES table. STATIC_VALUES may encode GNU-spec
knowledge for flags whose WinuxCmd help wraps or omits the value list.
"""

from __future__ import annotations

import argparse
import os
import re
import shutil
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUT_DIR = ROOT / "crates" / "niubash-runtime" / "assets" / "completions" / "winuxcmd"
DEFAULT_RUST_MODULE = ROOT / "crates" / "niubash-runtime" / "src" / "completion" / "winuxcmd_assets.rs"
DEFAULT_CORPUS_DIR = ROOT / "crates" / "niubash-runtime" / "tests" / "fixtures" / "winuxcmd-help-corpus"

GENERATED_HEADER = "# Generated by scripts/generate-winuxcmd-completions.py; do not edit by hand."
RUST_MODULE_HEADER = """\
// Generated by scripts/generate-winuxcmd-completions.py; do not edit by hand.
//! Embedded WinuxCmd applet completion definitions (compiled fallback layer).
//!
//! One `include_str!` entry per `assets/completions/winuxcmd/<applet>.toml`.
//! Load order contract (see `ExternalCompletionPlugin`): these defaults are
//! seeded at construction time; bundle definitions replace them per command,
//! and user completion dirs override everything.
#[allow(clippy::module_name_repetitions)]
pub static WINUXCMD_COMPLETION_TOMLS: &[(&str, &str)] = &["""
SAFE_COMMAND_RE = re.compile(r"^[A-Za-z0-9_.+\[\]-]+$")
INVENTORY_RE = re.compile(r"^\s{2,}([A-Za-z0-9_.+\[\]-]+)\s{2,}(.+?)\s*$")
OPTION_START_RE = re.compile(r"^\s{2,}(-[A-Za-z0-9?]|--[A-Za-z0-9][A-Za-z0-9_.-]*|-\d)")
OPTION_LINE_RE = re.compile(r"^\s{2,}(.+?)(?:\s{2,}(.+))?$")
# GNU projects (gawk 5.4.1 is the first live source, niubash#189) print
# options with SINGLE-TAB indentation in the classic dual-column layout:
# "\t-f progfile\t\t--file=progfile". WinuxCmd's own help indents with 2+
# spaces and separates the description column the same way, so the tab form
# is gated on a literal leading tab everywhere below: space-only transcripts
# parse exactly as before (the golden corpus is byte-identical proof).
TAB_OPTION_START_RE = re.compile(r"^\t(-[A-Za-z0-9?]|--[A-Za-z0-9][A-Za-z0-9_.-]*|-\d)")
TAB_OPTION_LINE_RE = re.compile(r"^\t(\S.*)$")
# GNU dual-column section header ("POSIX options:\t\tGNU long options:
# (standard)"): the first tab-delimited cell is the header text. An option
# line's first cell is empty (the line starts with the tab), so it never
# qualifies.
def is_tab_section_header(line: str) -> bool:
    if "\t" not in line:
        return False
    first_cell = line.split("\t", 1)[0]
    text = first_cell.strip()
    return bool(text) and text.endswith(":")
LONG_OPTION_RE = re.compile(r"^(--[A-Za-z0-9][A-Za-z0-9_.-]*)(.*)$")
SHORT_OPTION_RE = re.compile(r"^(-[A-Za-z0-9?][A-Za-z0-9_.-]*|-\d+)(.*)$")
VALUE_HINT_RE = re.compile(r"(?:^|[\s=\[<])(ARG|ARGS|NUM|NUMBER|FILE|FILES|DIR|DIRECTORY|PATH|PATTERN|WHEN|WORD|MODE|SIZE|TYPE|NAME|COMMAND|FORMAT|STYLE|COLOR|KEY|VALUE|N)(?:\]|\>|$|\s)", re.I)
POSSIBLE_VALUES_RE = re.compile(r"\[possible values?:\s*([^\]]+)\]", re.I)
QUOTED_VALUES_RE = re.compile(r"'([A-Za-z0-9_.+-]+)'")
# Bounded inline enumeration: "how to handle directories: read, recurse, skip".
# Requires 2-6 single lowercase words after a colon; connectives are dropped.
COLON_ENUM_RE = re.compile(r":\s+([a-z0-9_-]+(?:,\s+[a-z0-9_-]+)+)\.?(?:\s|$)")
COLON_ENUM_STOPWORDS = {"or", "and", "the", "of", "e.g", "i.e"}
FOOTER_RE = re.compile(r"^WinuxCmd is a Windows implementation\b")
SECTION_END_HEADERS = {
    "exit status:",
    "examples:",
    "available commands:",
    "commands:",
    "arguments:",
    "options:",
    "flags:",
}


